"""Equivalence checks of optimised monitors (``docs/strategies.md``, rule 2).

:func:`equivalence_check` gives the files of an SBY job that proves the monitor of a
machine in an optimised form equal to its direct (canonical) monitor, within the form's
scope (:func:`sva2yosys.optimize.forms.scope`):

- ``monitors.sv``: the direct monitor ``<name>_direct`` and the optimised one ``<name>``;
- ``miter.sv``: module ``<name>_equiv``. Its inputs are the monitors' clock and signal
  ports, so SBY leaves them free at every step. Both monitors are instantiated with
  ``CHECK = 0``. The miter asserts, at every step, that ``fail`` and ``success`` are
  equal. For a form exact only up to the first failure, it asserts the same equality of
  ``fail`` and ``success`` up to and including the first failure of the direct monitor (a
  sticky register), and nothing afterwards;
- ``equivalence.sby``: ``mode prove`` with ``abc pdr``, reading both files with
  ``read_verilog -formal -sv``.

sva2yosys never runs SBY itself; the test suite runs these jobs, and users can run them
for their own monitors (CLI ``--equivalence``).
"""

from __future__ import annotations

from sva2yosys.codegen.systemverilog import (
    declare,
    monitor_module,
    monitor_port_types,
)
from sva2yosys.optimize.forms import Form, Scope, scope
from sva2yosys.temporal.machine import Machine

_SBY = """[tasks]
prove

[options]
mode prove

[engines]
abc pdr

[script]
read_verilog -formal -sv monitors.sv miter.sv
prep -top {top}

[files]
monitors.sv
miter.sv
"""


def equivalence_check(machine: Machine, name: str, form: Form) -> dict[str, str]:
    """The files (name -> text) of the equivalence job for ``machine`` in ``form``.

    Raises:
        ValueError: ``form`` is ``DIRECT`` or does not apply to ``machine``.
    """
    if form is Form.DIRECT:
        raise ValueError("the direct form is the reference; there is nothing to check")
    optimised = monitor_module(machine, name, form)
    direct = monitor_module(machine, f"{name}_direct", Form.DIRECT)
    types = monitor_port_types(machine)
    top = f"{name}_equiv"
    ports = ["    input logic clk"]
    ports.extend(f"    input {declare(value_type, f'i{i}')}" for i, value_type in enumerate(types))
    connections = "".join(f", .i{i}(i{i})" for i in range(len(types)))
    lines = [
        "// generated by sva2yosys: equivalence of an optimised monitor with the direct one",
        f"// form: {form.value} (compared at {scope(form).value})",
        f"module {top} (",
        ",\n".join(ports),
        ");",
        "    logic fail_d, success_d, fail_o, success_o;",
        f"    {name}_direct #(.CHECK(1'b0)) u_direct (.clk(clk){connections},"
        " .fail(fail_d), .success(success_d));",
        f"    {name} #(.CHECK(1'b0)) u_optimised (.clk(clk){connections},"
        " .fail(fail_o), .success(success_o));",
    ]
    if scope(form) is Scope.EVERY_SAMPLE:
        lines.append("    always @* assert (fail_d == fail_o && success_d == success_o);")
    else:
        lines.extend(
            [
                "    logic failed_before = 1'b0;  // the direct monitor has failed before",
                "    always @(posedge clk) if (fail_d) failed_before <= 1'b1;",
                "    always @* assert (failed_before"
                " || (fail_d == fail_o && success_d == success_o));",
            ]
        )
    lines.append("endmodule")
    return {
        "monitors.sv": direct + "\n" + optimised,
        "miter.sv": "\n".join(lines) + "\n",
        "equivalence.sby": _SBY.format(top=top),
    }
